class I18nManager:
    _instance = None

    def __new__(cls, *args, **kwargs):
        if not cls._instance:
            cls._instance = super().__new__(cls)
            cls._instance._initialized = False
        return cls._instance

    def __init__(self, current_lang="auto"):
        if getattr(self, "_initialized", False):
            if current_lang != "auto":
                self.set_language(current_lang)
            return

        self._initialized = True
        self.current_lang = "en"
        self.set_language(current_lang)

    def _detect_system_language(self) -> str:
        try:
            for env_var in ('LC_ALL', 'LC_MESSAGES', 'LANG'):
                val = os.environ.get(env_var)
                if val:
                    code = val.split('.')[0].split('_')[0].lower()
                    if code in SUPPORTED_LANGUAGES:
                        return code
            
            loc = locale.getdefaultlocale()[0]
            if loc:
                code = loc.split('_')[0].lower()
                if code in SUPPORTED_LANGUAGES:
                    return code
        except Exception:
            pass
        return "en"

    def set_language(self, lang_code: str):
        if not lang_code or lang_code == "auto":
            self.current_lang = self._detect_system_language()
        elif lang_code in SUPPORTED_LANGUAGES:
            self.current_lang = lang_code
        else:
            self.current_lang = "en"

    def get_language(self) -> str:
        return self.current_lang

    def t(self, key: str, **kwargs) -> str:
        lang_dict = TRANSLATIONS.get(self.current_lang, TRANSLATIONS["en"])
        val = lang_dict.get(key, TRANSLATIONS["en"].get(key, key))
        if kwargs:
            try:
                return val.format(**kwargs)
            except Exception:
                return val
        return val


