def get_emoji_ru_name(char: str, en_name: str, direct_ru: list = None) -> str:
    """Return a clean, short, beautiful Russian title for the emoji."""
    if char in RU_EMOJI_NAMES:
        return RU_EMOJI_NAMES[char]
    if direct_ru and len(direct_ru) > 0:
        return direct_ru[0].capitalize()
    if en_name.startswith('flag: '):
        c_name = en_name[6:].strip()
        ru_c = RU_COUNTRY_NAMES.get(c_name, c_name)
        return f'Флаг: {ru_c}'
    if en_name == 'chequered flag':
        return 'Финишный флаг'
    if en_name == 'rainbow flag':
        return 'Радужный флаг'
    if en_name == 'pirate flag':
        return 'Пиратский флаг'
    return en_name.capitalize()
