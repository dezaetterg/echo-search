class EmojiProvider(BaseProvider):
    def __init__(self, history_manager):
        super().__init__(history_manager)
        self.emojis = []
        self._load_db()

    def _load_db(self):
        try:
            db_path = os.path.join(os.path.dirname(__file__), '..', 'emoji.json')
            if not os.path.exists(db_path):
                system_db = "/usr/share/echo-search/emoji.json"
                if os.path.exists(system_db):
                    db_path = system_db
            if os.path.exists(db_path):
                with open(db_path, 'r', encoding='utf-8') as f:
                    data = json.load(f)
                    for item in data:
                        char = item.get("emoji")
                        if not char:
                            continue
                        name = item.get("description", "")
                        category = item.get("category", "Other")
                        aliases = item.get("aliases", [])
                        tags = item.get("tags", [])
                        keywords = set(aliases + tags)
                        
                        # Добавляем русские переводы из базового словаря по полным словам
                        for tag in list(keywords):
                            words = set(re.split(r'[^a-zA-Z0-9]+', tag.lower()))
                            for en_k, ru_vals in COMMON_RU_TRANSLATIONS.items():
                                if en_k in words:
                                    for ru_v in ru_vals:
                                        keywords.add(ru_v)
                                        
                        # Добавляем прямые русские синонимы по символу эмодзи
                        if char in RU_EMOJI_SYNONYMS:
                            for ru_syn in RU_EMOJI_SYNONYMS[char]:
                                keywords.add(ru_syn)
                                
                        kw_list = list(keywords)
                        direct_ru_list = RU_EMOJI_SYNONYMS.get(char, [])
                        self.emojis.append({
                            "char": char,
                            "name": name,
                            "name_lower": name.lower(),
                            "category": category,
                            "kw": kw_list,
                            "kw_lower": [k.lower() for k in kw_list],
                            "direct_ru": direct_ru_list,
                            "direct_ru_lower": [r.lower() for r in direct_ru_list]
                        })
        except Exception as e:
            print("Failed to load emoji DB:", e)
            
        self._load_characters()

